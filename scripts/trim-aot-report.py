#!/usr/bin/env python3
"""Compare Chrysalis.Codec Trim & AOT analyzer diagnostics against a base git ref."""

from __future__ import annotations

import argparse
from collections import Counter
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import xml.sax.saxutils

CANARY_REL = "src/Chrysalis.Codec/__TrimAotCanary.g.cs"
CODEC_CSPROJ = "src/Chrysalis.Codec/Chrysalis.Codec.csproj"
CODEGEN_CSPROJ = "src/Chrysalis.Codec.CodeGen/Chrysalis.Codec.CodeGen.csproj"
ASSETS_REL = "src/Chrysalis.Codec/obj/project.assets.json"
CANARY_SOURCE = """// <auto-generated/>
#nullable enable
using System.Diagnostics.CodeAnalysis;

namespace Chrysalis.Codec;

internal static class __TrimAotCanary
{
    [RequiresUnreferencedCode("X11_TRIM_CANARY")]
    internal static void TriggerTrim() { }

    [RequiresDynamicCode("X11_AOT_CANARY")]
    internal static void TriggerAot() { }

    internal static void InvokeCanaries()
    {
        TriggerTrim();
        TriggerAot();
    }
}
"""

IL_DIAG_RE = re.compile(r"^(?P<path>.+?)(?:\(\d+(?:,\d+)*\))?:\s*(?:warning|error)\s+(?P<code>IL[23]\d{3}):\s*(?P<msg>.+)$")
CODED_NON_IL_ERR_RE = re.compile(r"\berror\s+(?!IL[23]\d{3}\b)[A-Za-z]+\d+\s*:")
UNCODED_ERR_RE = re.compile(r"(?:^|\s)error\s*:")
BANNER_RE = re.compile(r"^\s*Build\s+(?P<status>FAILED|succeeded)\.\s*$")


def default_command_runner(cmd: list[str], *, cwd: Path, env: dict[str, str], stdout_to_stderr: bool = True) -> tuple[int, str]:
    proc = subprocess.run(
        cmd,
        cwd=cwd,
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT if stdout_to_stderr else subprocess.PIPE,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    return proc.returncode, proc.stdout


def stage_base_tree(candidate_root: Path, base_ref: str, dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    archive = subprocess.run(
        ["git", "-C", str(candidate_root), "archive", base_ref],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if archive.returncode != 0:
        raise RuntimeError(f"git archive {base_ref} failed: {archive.stderr.decode('utf-8', 'replace')}")
    untar = subprocess.run(["tar", "-xf", "-", "-C", str(dest)], input=archive.stdout, stderr=subprocess.PIPE, check=False)
    if untar.returncode != 0:
        raise RuntimeError(f"tar extract failed: {untar.stderr.decode('utf-8', 'replace')}")


def stage_candidate_tree(candidate_root: Path, dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    names = subprocess.check_output(
        ["git", "-C", str(candidate_root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
    )
    for raw_name in filter(None, names.split(b"\0")):
        rel_str = os.fsdecode(raw_name)
        rel = Path(rel_str)
        if rel.parts[0] == ".git" or rel_str.startswith("benchmarks/out/") or any(p in ("obj", "bin") for p in rel.parts):
            continue
        src = candidate_root / rel
        if src.is_symlink() or not src.is_file():
            continue
        dst = dest / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)


def normalize_text(text: str, stage_root: Path, *, is_path: bool = False) -> str:
    roots = sorted({stage_root.as_posix().rstrip("/"), stage_root.resolve().as_posix().rstrip("/")}, key=len, reverse=True)
    norm = text.replace("\\", "/")
    if is_path:
        for prefix in roots:
            if not prefix:
                continue
            if norm == prefix:
                norm = ""
                break
            if norm.startswith(prefix + "/"):
                norm = norm[len(prefix) + 1:]
                break
        while norm.startswith("./"):
            norm = norm[2:]
        return norm
    for prefix in roots:
        if prefix:
            escaped = re.escape(prefix)
            norm = re.sub(rf"(?<![A-Za-z0-9_./-]){escaped}/", "", norm)
            norm = re.sub(rf"(?<![A-Za-z0-9_./-]){escaped}(?![A-Za-z0-9_./-])", "", norm)
    return norm


def parse_build_output(log_text: str, stage_root: Path) -> tuple[Counter[tuple[str, str, str]], dict[str, bool], bool]:
    counts: Counter[tuple[str, str, str]] = Counter()
    canaries = {"IL2026": False, "IL3050": False}
    saw_banner = False
    saw_succeeded = False
    for raw_line in log_text.splitlines():
        banner_match = BANNER_RE.match(raw_line)
        if banner_match:
            saw_banner = True
            saw_succeeded = banner_match.group("status") == "succeeded"
            break
        if CODED_NON_IL_ERR_RE.search(raw_line) or UNCODED_ERR_RE.search(raw_line):
            raise RuntimeError(f"Non-IL build error: {raw_line.strip()}")
        match = IL_DIAG_RE.match(raw_line.strip())
        if not match:
            continue
        code = match.group("code")
        path = normalize_text(match.group("path").strip(), stage_root, is_path=True)
        msg = normalize_text(match.group("msg").strip(), stage_root, is_path=False)
        if path == CANARY_REL and code == "IL2026" and "X11_TRIM_CANARY" in msg and not canaries["IL2026"]:
            canaries["IL2026"] = True
            continue
        if path == CANARY_REL and code == "IL3050" and "X11_AOT_CANARY" in msg and not canaries["IL3050"]:
            canaries["IL3050"] = True
            continue
        counts[(code, path, msg)] += 1

    if not saw_banner:
        raise RuntimeError("Missing MSBuild completion banner ('Build FAILED.' or 'Build succeeded.')")
    if not (canaries["IL2026"] and canaries["IL3050"]):
        raise RuntimeError(f"Missing required trim/AOT execution canary: {canaries}")
    return counts, canaries, saw_succeeded


def verify_illink_assets(stage_root: Path) -> None:
    assets_path = stage_root / ASSETS_REL
    if not assets_path.is_file():
        raise RuntimeError(f"Missing assets file: {assets_path}")
    assets = json.loads(assets_path.read_text(encoding="utf-8-sig"))
    libs = assets.get("libraries", {})
    if not any(key.lower().startswith("microsoft.net.illink.tasks/") for key in libs):
        raise RuntimeError(f"Microsoft.NET.ILLink.Tasks missing from {assets_path}")


def build_side(stage_root: Path, nuget_config: Path, command_runner) -> tuple[Counter[tuple[str, str, str]], dict[str, bool]]:
    canary_file = stage_root / CANARY_REL
    canary_file.parent.mkdir(parents=True, exist_ok=True)
    canary_file.write_text(CANARY_SOURCE, encoding="utf-8")
    env = dict(os.environ, DOTNET_CLI_TELEMETRY_OPTOUT="1", DOTNET_NOLOGO="1")
    common_flags = ["-m:3", "-nodeReuse:false", "--disable-build-servers", "-p:UseSharedCompilation=false"]
    trim_flags = ["-p:EnableTrimAnalyzer=true", "-p:EnableAotAnalyzer=true"]

    steps = [
        ["dotnet", "restore", CODEGEN_CSPROJ, "--configfile", str(nuget_config), *common_flags],
        ["dotnet", "build", CODEGEN_CSPROJ, "-c", "Release", "--no-restore", *common_flags],
        ["dotnet", "restore", CODEC_CSPROJ, "--no-dependencies", "--configfile", str(nuget_config), *common_flags, *trim_flags],
    ]
    for cmd in steps:
        rc, out = command_runner(cmd, cwd=stage_root, env=env, stdout_to_stderr=True)
        if rc != 0:
            raise RuntimeError(f"Command failed ({rc}): {' '.join(cmd)}\n{out}")

    verify_illink_assets(stage_root)
    build_cmd = ["dotnet", "build", CODEC_CSPROJ, "-c", "Release", "--no-restore", "--no-dependencies", "--no-incremental", *common_flags, *trim_flags, "-v:minimal"]
    rc, out = command_runner(build_cmd, cwd=stage_root, env=env, stdout_to_stderr=True)
    counts, canaries, saw_succeeded = parse_build_output(out, stage_root)
    if (rc == 0) != saw_succeeded:
        raise RuntimeError(f"Step 4 exit code ({rc}) disagrees with build banner (succeeded={saw_succeeded}):\n{out}")
    return counts, canaries


def serialize_diff(diff: Counter[tuple[str, str, str]]) -> list[dict[str, object]]:
    return [{"code": code, "path": path, "message": msg, "count": count}
            for (code, path, msg), count in sorted(diff.items()) if count > 0]


def run_report(
    candidate_root: Path,
    base_ref: str,
    *,
    json_path: Path | None = None,
    nuget_packages: Path | None = None,
    command_runner=default_command_runner,
) -> tuple[int, dict[str, object]]:
    nuget_root = nuget_packages or Path(os.environ.get("NUGET_PACKAGES") or (Path.home() / ".nuget/packages"))
    if not nuget_root.is_dir() or not any(p.name.lower() == "microsoft.net.illink.tasks" for p in nuget_root.iterdir()):
        raise RuntimeError(f"Offline NuGet cache lacks microsoft.net.illink.tasks: {nuget_root}")

    with tempfile.TemporaryDirectory(prefix="chrysalis-trim-aot-") as tmp:
        run_root = Path(tmp)
        base_stage = run_root / "base"
        cand_stage = run_root / "candidate"
        nuget_config = run_root / "offline.NuGet.Config"
        escaped_nuget = xml.sax.saxutils.escape(str(nuget_root), {'"': "&quot;", "'": "&apos;"})
        nuget_config.write_text(
            f'<?xml version="1.0" encoding="utf-8"?>\n<configuration>\n  <packageSources>\n    <clear />\n    <add key="offline" value="{escaped_nuget}" />\n  </packageSources>\n</configuration>\n',
            encoding="utf-8",
        )
        stage_base_tree(candidate_root, base_ref, base_stage)
        stage_candidate_tree(candidate_root, cand_stage)

        base_counts, base_canaries = build_side(base_stage, nuget_config, command_runner)
        cand_counts, cand_canaries = build_side(cand_stage, nuget_config, command_runner)

    added = cand_counts - base_counts
    removed = base_counts - cand_counts
    all_codes = sorted({k[0] for k in base_counts} | {k[0] for k in cand_counts})
    by_code = {
        code: {
            "base": sum(v for k, v in base_counts.items() if k[0] == code),
            "candidate": sum(v for k, v in cand_counts.items() if k[0] == code),
        }
        for code in all_codes
    }
    report: dict[str, object] = {
        "base_ref": base_ref,
        "canaries_verified": {"base": base_canaries, "candidate": cand_canaries},
        "base_total": sum(base_counts.values()),
        "candidate_total": sum(cand_counts.values()),
        "added": serialize_diff(added),
        "removed": serialize_diff(removed),
        "by_code": by_code,
    }
    if json_path is not None:
        json_path.parent.mkdir(parents=True, exist_ok=True)
        json_path.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    return (1 if report["added"] else 0), report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--candidate", required=True, type=Path, help="Path to candidate repository")
    parser.add_argument("--base", required=True, help="Base git commit/ref to compare against")
    parser.add_argument("--json", type=Path, help="Optional JSON output path")
    args = parser.parse_args()
    code, report = run_report(args.candidate.resolve(), args.base, json_path=args.json)
    print(f"Trim/AOT report vs {args.base}: base={report['base_total']}, candidate={report['candidate_total']}, added={len(report['added'])}, removed={len(report['removed'])}")
    return code


if __name__ == "__main__":
    sys.exit(main())
