        private static StringBuilder EmitCborListPartialProperty(StringBuilder sb, CborListPropertyMetadata list, string fieldRef)
        {
            if (list.IsNullable)
            {
                _ = sb.AppendLine($"if ({fieldRef}.Length == 0 || {fieldRef}.Span[0] is 0xF6 or 0xF7) return default;");
            }

            string? itemReader = GetPrimitiveReaderRef(list.ItemType) ?? (list.HasDirectItemReader ? $"{list.ItemType}.Read" : null);
            if (itemReader is not null)
            {
                _ = sb.AppendLine($"global::Chrysalis.Codec.Serialization.CborListReaderCache<{list.ItemType}>.Reader ??= {itemReader};");
            }
            return sb.AppendLine($"return {list.Type}.Read({fieldRef});");
        }

        private static string? GetPrimitiveReaderRef(string cleanType)
        {
            const string prefix = "global::Chrysalis.Codec.Serialization.CborPrimitiveReaders";
            return cleanType switch
            {
                "int" => $"{prefix}.ReadInt32",
                "uint" => $"{prefix}.ReadUInt32",
                "long" => $"{prefix}.ReadInt64",
                "ulong" => $"{prefix}.ReadUInt64",
                "bool" => $"{prefix}.ReadBoolean",
                "string" => $"{prefix}.ReadString",
                "float" => $"{prefix}.ReadSingle",
                "double" => $"{prefix}.ReadDouble",
                "byte[]" => $"{prefix}.ReadByteArray",
                "ReadOnlyMemory<byte>" or "System.ReadOnlyMemory<byte>" or "global::System.ReadOnlyMemory<byte>"
                    => $"{prefix}.ReadByteMemory",
                _ => null
            };
        }

        private static ICborSerializerEmitter GetEmitter(SerializableTypeMetadata metadata, ImmutableDictionary<string, SerializableTypeMetadata>? typeRegistry = null) => metadata.SerializationType switch
        {
            SerializationType.Constr => new ConstructorEmitter(),
            SerializationType.Container => new ContainerEmitter(),
            SerializationType.List => new ListEmitter(),
            SerializationType.Map => new MapEmitter(),
            SerializationType.Union => new UnionEmitter(typeRegistry),
            _ => throw new NotSupportedException($"Serialization type {metadata.SerializationType} is not supported.")
        };

        public static int ResolveTag(int? index)
        {
            if (index is null or < 0)
            {
                return -1;
            }
            else
            {
                int finalIndex = index > 6 ? 1280 - 7 : 121;
                return finalIndex + index.Value;
            }
        }

        private static StringBuilder EmitByteMemorySlot(StringBuilder sb, string cleanType, string fieldRef, string variable)
        {
            bool encoded = !IsReadOnlyMemoryByteType(cleanType);
            _ = sb.AppendLine($"{(encoded ? CborEncodeValueFullName : "global::System.ReadOnlyMemory<byte>")} {variable};");
            return EmitByteMemoryRead(sb, "_r", fieldRef, $"{variable} =", encoded);
        }

